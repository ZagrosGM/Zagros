def _render_with_template(page: PortalPage, template_name: str,
                          templates_dir: str | None) -> str | None:
    """Operator template, or ``None`` so the caller serves the built-in page.

    A subscriber must never be shown a broken page because an operator
    uploaded one: every failure here degrades to the built-in renderer.
    """
    if not templates_dir:
        return None
    try:
        from app.portal.templates_store import render_template

        return render_template(templates_dir, template_name,
                               _template_context(page))
    except Exception as exc:  # noqa: BLE001 — presentation must not raise
        logger.warning("custom subscription template %r unavailable (%s) — "
                       "serving the built-in page", template_name, exc)
        return None


def render_with_template_strict(page: PortalPage, template_name: str,
                                templates_dir: str) -> str:
    """Preview path: render the operator template or raise
    :class:`app.portal.templates_store.TemplateError` with the reason."""
    from app.portal.templates_store import render_template

    return render_template(templates_dir, template_name,
                           _template_context(page), strict=True) or ""


def render_page_html(page: PortalPage, template_name: str | None = None,
                     *, templates_dir: str | None = None) -> str:
    """Render a complete, self-contained HTML document.

    ``template_name`` selects an operator-uploaded template (Subscriptions
    section); when it is missing or broken, the built-in page is served.
    The application-login page is never replaced by a template: in that
    mode not a single byte of configuration material may leave the panel,
    and an operator template cannot be audited for that.
    """
    if template_name and page.kind is PageKind.PORTAL:
        custom = _render_with_template(page, template_name, templates_dir)
        if custom is not None:
            return custom
    body = _render_portal(page) if page.kind is PageKind.PORTAL else _render_app_page(page)
    support = ""
    if page.support_url:
        support = (
            f' · <a href="{_esc(page.support_url)}" rel="noopener">'
            f'{_esc(_t(page, "support"))}</a>'
        )
    footer = (
        f'<div class="footer">{_esc(_t(page, "footer_powered"))} '
        f"<b>{_esc(page.brand)}</b>{support}</div>"
    )
    return f"""<!doctype html>
<html lang="{_esc(page.lang)}" dir="{_esc(page.direction)}" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>{_esc(page.brand)} · {_esc(page.title or page.user.username)}</title>
<style>{_CSS}</style>
</head>
<body>
<div class="wrap">
<div class="header"><div class="brand">{_LOGO}<span>{_esc(page.brand)}</span></div>{_THEME_BTN}</div>
{body}
{footer}
</div>
<script>{_JS}</script>
</body>
</html>"""
