export type TParams = Record<string, string | number>;

// {placeholders} are substituted after lookup so translators can reorder them,
// which RTL phrasing frequently requires.
function interpolate(text: string, params?: TParams): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : whole);
}

export function translate(locale: "en" | "fa", key: Key, params?: TParams): string {
  const text = (locale === "fa" ? fa[key] : en[key]) ?? en[key] ?? key;
  return interpolate(text, params);
}

export function useT() {
  const locale = useUI((s) => s.locale);
  return (key: Key, params?: TParams): string => translate(locale, key, params);
}

// Same lookup, but for strings whose value is only known at runtime — status
// enums and messages that arrive from the API. Anything the dictionary knows is
// localised; anything else is passed through untouched, so an unrecognised
// server message still reaches the operator instead of being swallowed.
export function useTDynamic() {
  const locale = useUI((s) => s.locale);
  return (text: string | null | undefined, params?: TParams): string => {
    if (!text) return "";
    return Object.prototype.hasOwnProperty.call(en, text)
      ? translate(locale, text as Key, params)
      : interpolate(text, params);
  };
}
