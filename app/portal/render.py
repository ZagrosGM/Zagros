def _t(page: PortalPage, key: str) -> str:
    table = _STRINGS.get(page.lang, _STRINGS["en"])
    return table.get(key, _STRINGS["en"].get(key, key))


def _esc(text: object) -> str:
    return html.escape(str(text), quote=True)


def _fmt_bytes(n: int | None, unlimited: str = "∞") -> str:
    if n is None:
        return unlimited
    value = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            if unit == "B":
                return f"{int(value)} {unit}"
            return f"{value:.2f} {unit}"
        value /= 1024
    return f"{value:.2f} PB"


def _fmt_date(dt: datetime.datetime | None, none_text: str) -> str:
    return dt.strftime("%Y/%m/%d") if dt else none_text


def _days_left(dt: datetime.datetime | None) -> int | None:
    if dt is None:
        return None
    delta = dt - datetime.datetime.now(datetime.timezone.utc)
    return delta.days


def _qr_svg(content: str) -> str:
    matrix = encode_matrix(content)
    return to_svg(matrix, module_px=6)


def _data_uri(mime: str, content: str) -> str:
    return f"data:{mime};base64,{base64.b64encode(content.encode('utf-8')).decode('ascii')}"


