export function translate(locale: "en" | "fa", key: Key): string {
  return (locale === "fa" ? fa[key] : en[key]) ?? en[key] ?? key;
}

export function useT() {
  const locale = useUI((s) => s.locale);
  return (key: Key): string => translate(locale, key);
}
