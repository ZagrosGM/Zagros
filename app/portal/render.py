def _render_artifact(page: PortalPage, artifact) -> str:
    if artifact.kind is ArtifactKind.LINK:
        return _render_link_artifact(page, artifact)
    if artifact.kind is ArtifactKind.FILE:
        href = _data_uri(artifact.mime, artifact.content)
        qr = ""
        if artifact.qr:
            qr = (
                f'<details><summary><button class="btn ghost" type="button">{_esc(_t(page, "show_qr"))}</button></summary>'
                f'<div class="qrbox">{_qr_svg(artifact.content)}</div></details>'
            )
        return (
            f'<div class="artifact"><div class="lbl">{_esc(artifact.label)}</div>'
            f'<div class="row"><a class="btn" download="{_esc(artifact.filename)}" '
            f'href="{href}">{_esc(_t(page, "download_file"))} · {_esc(artifact.filename)}</a>'
            f"<div>{qr}</div></div></div>"
        )
    if artifact.kind is ArtifactKind.FIELDS:
        rows: list[str] = []
        for i, field in enumerate(artifact.fields):
            fid = f"f{abs(hash((field.key, field.value))) % 10**8}_{i}"
            if field.secret:
                mask = "•" * min(10, max(6, len(field.value)))
                value_html = (
                    f'<span id="{fid}" data-value="{_esc(field.value)}" data-mask="{mask}" '
                    f'data-masked="1">{mask}</span> '
                    f'<button class="mini" data-target="{fid}" data-show="{_esc(_t(page, "reveal"))}" '
                    f'data-hide="{_esc(_t(page, "hide"))}" onclick="zgReveal(this)">{_esc(_t(page, "reveal"))}</button>'
                )
            else:
                value_html = _esc(field.value)
            copy_btn = ""
            if field.copyable:
                copy_btn = (
                    f'<button class="mini" data-done="{_esc(_t(page, "copied"))}" '
                    f'onclick="zgCopy(this, decodeURIComponent(this.dataset.v))" '
                    f'data-v="{_copy_attr(field.value)}">'
                    f'{_esc(_t(page, "copy"))}</button>'
                )
            rows.append(f"<tr><td class='k'>{_esc(field.label)}</td>"
                        f"<td class='v'>{value_html} {copy_btn}</td></tr>")
        note = f'<div class="note">{_esc(artifact.note)}</div>' if artifact.note else ""
        return (
            f'<div class="artifact"><div class="lbl">{_esc(artifact.label)}</div>'
            f'<table class="fields">{"".join(rows)}</table>{note}</div>'
        )
    # NOTE
    return f'<div class="note"><b>{_esc(artifact.label)}</b> — {_esc(artifact.note or "")}</div>'


def _render_section(page: PortalPage, section: DeliverySection) -> str:
    artifacts = "".join(_render_artifact(page, a) for a in section.artifacts)
    chips = f'<span class="chip">{_esc(section.protocol)}</span>'
    if section.engine:
        chips += f'<span class="chip">{_esc(section.engine)}</span>'
