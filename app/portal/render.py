def _status_pill(page: PortalPage) -> str:
    statuses = _STRINGS.get(page.lang, _STRINGS["en"])["stats_status"]
    label = statuses.get(page.user.status, page.user.status)
    tone = {"active": "ok", "on_hold": "warn"}.get(page.user.status, "bad")
    return f'<span class="pill {tone}">{_esc(label)}</span>'


def _copy_attr(text: str) -> str:
    """data-v attribute carrying URL-encoded text for zgCopy()."""
    from urllib.parse import quote

    return _esc(quote(text, safe=""))


def _render_link_artifact(page: PortalPage, artifact) -> str:
    url = artifact.content
    qr = ""
    if artifact.qr:
        qr = (
            f'<details><summary><button class="btn ghost" type="button">{_esc(_t(page, "show_qr"))}</button></summary>'
            f'<div class="qrbox">{_qr_svg(url)}</div></details>'
        )
    note = f'<div class="note">{_esc(artifact.note)}</div>' if artifact.note else ""
    return (
        f'<div class="artifact"><div class="lbl">{_esc(artifact.label)}</div>'
        f'<div class="linkbox">{_esc(url)}</div>'
        f'<div class="row"><div>{qr}</div>'
        f'<button class="btn" data-done="{_esc(_t(page, "copied"))}" '
        f'data-v="{_copy_attr(url)}" '
        f'onclick="zgCopy(this, decodeURIComponent(this.dataset.v))">'
        f"{_esc(_t(page, 'copy'))}</button></div>{note}</div>"
    )


def _render_artifact(page: PortalPage, artifact) -> str:
    if artifact.kind is ArtifactKind.LINK:
        return _render_link_artifact(page, artifact)
    if artifact.kind is ArtifactKind.FILE:
        href = _data_uri(artifact.mime, artifact.content)
        qr = ""
        if artifact.qr:
            qr = (
                f'<details><summary><button class="btn ghost" type="button">{_esc(_t(page, "show_qr"))}</button></summary>'
                f'<div class="qrbox">{_qr_svg(artifact.content)}</div></details>'
            )
        return (
            f'<div class="artifact"><div class="lbl">{_esc(artifact.label)}</div>'
            f'<div class="row"><a class="btn" download="{_esc(artifact.filename)}" '
            f'href="{href}">{_esc(_t(page, "download_file"))} · {_esc(artifact.filename)}</a>'
            f"<div>{qr}</div></div></div>"
        )
    if artifact.kind is ArtifactKind.FIELDS:
        rows: list[str] = []
        for i, field in enumerate(artifact.fields):
            fid = f"f{abs(hash((field.key, field.value))) % 10**8}_{i}"
            if field.secret:
                mask = "•" * min(10, max(6, len(field.value)))
                value_html = (
                    f'<span id="{fid}" data-value="{_esc(field.value)}" data-mask="{mask}" '
                    f'data-masked="1">{mask}</span> '
                    f'<button class="mini" data-target="{fid}" data-show="{_esc(_t(page, "reveal"))}" '
                    f'data-hide="{_esc(_t(page, "hide"))}" onclick="zgReveal(this)">{_esc(_t(page, "reveal"))}</button>'
                )
            else:
                value_html = _esc(field.value)
            copy_btn = ""
            if field.copyable:
                copy_btn = (
                    f'<button class="mini" data-done="{_esc(_t(page, "copied"))}" '
                    f'onclick="zgCopy(this, decodeURIComponent(this.dataset.v))" '
                    f'data-v="{_copy_attr(field.value)}">'
                    f'{_esc(_t(page, "copy"))}</button>'
                )
            rows.append(f"<tr><td class='k'>{_esc(field.label)}</td>"
                        f"<td class='v'>{value_html} {copy_btn}</td></tr>")
        note = f'<div class="note">{_esc(artifact.note)}</div>' if artifact.note else ""
        return (
            f'<div class="artifact"><div class="lbl">{_esc(artifact.label)}</div>'
            f'<table class="fields">{"".join(rows)}</table>{note}</div>'
        )
    # NOTE
    return f'<div class="note"><b>{_esc(artifact.label)}</b> — {_esc(artifact.note or "")}</div>'


def _render_section(page: PortalPage, section: DeliverySection) -> str:
    artifacts = "".join(_render_artifact(page, a) for a in section.artifacts)
    chips = f'<span class="chip">{_esc(section.protocol)}</span>'
    if section.engine:
        chips += f'<span class="chip">{_esc(section.engine)}</span>'
    note = f'<div class="note">{_esc(section.note)}</div>' if section.note else ""
    return (
        f'<div class="card"><div class="section-title"><h2>{_esc(section.title)}</h2>{chips}</div>'
        f"{note}{artifacts}</div>"
    )


def _render_portal(page: PortalPage) -> str:
    u = page.user
    unlimited = _t(page, "unlimited")
    ratio = u.usage_ratio
    bar = ""
    if ratio is not None:
        pct = int(round(ratio * 100))
        bar = f'<div class="bar" role="progressbar" aria-valuenow="{pct}"><div style="width:{pct}%"></div></div>'
    days = _days_left(u.expire_at)
    expiry_extra = ""
    if days is not None:
        expiry_extra = (
            f' <span style="opacity:.85">· {days} {_esc(_t(page, "days_left"))}</span>'
            if days >= 0 else f' <span style="opacity:.85">· {_esc(_t(page, "expired"))}</span>'
        )
    online = _t(page, "online_now") if u.online else ""
    hero_sub = f"{_esc(_t(page, 'subscription_of'))} <b>{_esc(u.username)}</b>"
    if online:
        hero_sub += f' · <span title="">{_esc(online)}</span>'

    stats = (
        f'<div class="grid">'
        f'<div class="stat"><div class="k">{_esc(_t(page, "status"))}</div>'
        f'<div class="v">{_status_pill(page)}</div></div>'
        f'<div class="stat"><div class="k">{_esc(_t(page, "used"))}</div>'
        f'<div class="v" dir="ltr">{_fmt_bytes(u.used_bytes, unlimited)}</div></div>'
        f'<div class="stat"><div class="k">{_esc(_t(page, "remaining"))}</div>'
        f'<div class="v" dir="ltr">{_fmt_bytes(u.remaining_bytes, unlimited)}</div></div>'
        f'<div class="stat"><div class="k">{_esc(_t(page, "expiry"))}</div>'
        f'<div class="v">{_fmt_date(u.expire_at, _t(page, "no_expiry"))}{expiry_extra}</div></div>'
        f"</div>{bar}"
    )
    sections_html = ""
    if page.sections:
        head = f'<div class="card"><div class="section-title"><h2>{_esc(_t(page, "protocols_hint"))}</h2></div></div>'
        sections_html = head + "".join(_render_section(page, s) for s in page.sections)
    notes = "".join(f'<div class="note">{_esc(n)}</div>' for n in page.notes)
    return f"""
<div class="hero"><h1>{_esc(page.brand)}</h1><div class="sub">{hero_sub}</div></div>
<div class="card">{stats}</div>
{notes}{sections_html}
"""


